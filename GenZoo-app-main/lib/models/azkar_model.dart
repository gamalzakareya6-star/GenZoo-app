class AzkarItem {
  final String id;
  final String title;
  final String arabicText;
  final String? translation;
  final String? virtue; // Reference / Benefit
  final int targetCount;
  final String category; // 'study', 'morning', 'evening', 'after_prayer', 'sleep', 'general'

  AzkarItem({
    required this.id,
    required this.title,
    required this.arabicText,
    this.translation,
    this.virtue,
    this.targetCount = 1,
    required this.category,
  });

  factory AzkarItem.fromMap(Map<String, dynamic> map, String id) {
    return AzkarItem(
      id: id,
      title: map['title'] ?? '',
      arabicText: map['arabicText'] ?? '',
      translation: map['translation'],
      virtue: map['virtue'],
      targetCount: (map['targetCount'] as num?)?.toInt() ?? 1,
      category: map['category'] ?? 'study',
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'title': title,
      'arabicText': arabicText,
      'translation': translation,
      'virtue': virtue,
      'targetCount': targetCount,
      'category': category,
    };
  }

