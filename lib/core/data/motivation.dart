    'إنجازك اليوم هديّة لنفسك في المستقبل.',
    'كن فخوراً بكل يوم ذاكرت فيه.',
    'علم الحيوان يكشف أسرار الحياة، استمتع باكتشافها.',
  ];

  static String phraseFor(DateTime day) {
    final n = DateTime(day.year, day.month, day.day).difference(DateTime(2024, 1, 1)).inDays;
    return phrases[n.abs() % phrases.length];
  }

  static String greeting(DateTime now) {
    final h = now.hour;
    if (h < 5) return 'ما زلت ساهراً؟ لا تنسَ الراحة 🌙';
    if (h < 12) return 'صباح الخير ☀️';
    if (h < 17) return 'نهارك سعيد 🌤️';
    if (h < 21) return 'مساء الخير 🌇';
    return 'مساء النور 🌙';
  }

  static String streakMessage(int days) {
    if (days >= 100) return '١٠٠ يوم متواصل! أنت أسطورة 🏆';
    if (days >= 60) return 'شهران من الالتزام! أنت قدوة لزملائك 🌟';
    if (days >= 30) return 'شهر كامل من المذاكرة اليومية! إنجاز رائع 🎉';
    if (days >= 14) return 'أسبوعان متواصلان، لا شيء يوقفك 💪';
    if (days >= 7) return 'أسبوع كامل! سلسلتك صارت قوية 🔥';
    if (days >= 3) return '$days أيام متتالية، استمر ولا تكسر السلسلة 🔥';
    if (days == 2) return 'يومان متتاليان، بداية قوية 👏';
    return 'بدأت سلسلتك اليوم، وكل رحلة تبدأ بخطوة 🔥';
  }

  static const List<String> taskDone = [
    'أحسنت! مهمة أنجزتها 👏',
    'ممتاز، خطوة أخرى نحو هدفك ✅',
    'عمل رائع، استمر 💪',
    'إنجاز جديد في رصيدك 🌟',
  ];

  static String taskDoneMessage(int seed) => taskDone[seed.abs() % taskDone.length];

  static String examMessage(String name, int daysLeft) {
    if (daysLeft <= 0) return 'امتحان $name اليوم، بالتوفيق! 🍀';
    if (daysLeft == 1) return 'امتحان $name غداً، راجع بهدوء ونَم مبكراً 🌙';
    if (daysLeft <= 3) return 'باقي $daysLeft أيام على امتحان $name، وقت التركيز 🎯';
    if (daysLeft <= 7) return 'باقي $daysLeft أيام على امتحان $name، نظّم مراجعتك 📚';
    return 'باقي $daysLeft يوماً على امتحان $name، ابدأ مبكراً وسترتاح لاحقاً ✨';
  }
}
