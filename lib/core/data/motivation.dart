    'لا تنتظر الحماس، ابدأ وسيأتي الحماس معك.',
    'عشر دقائق مذاكرة أفضل من ساعة تأجيل.',
    'أنت أقرب إلى هدفك مما تظن.',
    'كل صفحة تنهيها هي نقطة في رصيدك.',
    'المثابرة تغلب الموهبة حين تغيب المثابرة.',
    'اجعل مذاكرة اليوم أفضل من أمس ولو بقليل.',
    'من جدّ وجد، ومن زرع حصد.',
    'النجاح عادة صغيرة تتكرر كل يوم.',
    'لا تقارن بدايتك بنهاية غيرك.',
    'الراحة جزء من المذاكرة، لا تنسَ أن تستريح.',
    'اشرب ماء، خذ نفساً عميقاً، وكمّل.',
    'اليوم الصعب يمرّ، وما تعلمته يبقى.',
